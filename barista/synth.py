def generate(key, params=None, V=(0.01, 2.0), T=(300,), d=(10,), n_points=40, noise=0.03,
             dev=None, seed=0, both_polarities=False, sweep_back=False) -> pd.DataFrame:
    """Return a long-format DataFrame (V [V], I [A], T [K], d [nm]) generated by one mechanism."""
    m = REGISTRY[key]
    dev = dev if isinstance(dev, DeviceInfo) else DeviceInfo.from_dict(dev or {})
    p = {q.name: q.init for q in m.params}
    p.update(params or {})
    area = dev.area_m2 or 1e-12
    rng = np.random.default_rng(seed)
    pref = next((q.name for q in m.params if q.profile), None)
    rows = []
    Vg = np.geomspace(V[0], V[1], n_points)
    for TT in T:
        for dd in d:
            lnJ = m.lnJ(Vg, np.full_like(Vg, TT), np.full_like(Vg, dd * 1e-9), p, dev)
            if pref:
                lnJ = lnJ + LN10 * p[pref]
            I = np.exp(lnJ) * area * np.exp(noise * rng.standard_normal(len(Vg)))
            for v, i in zip(Vg, I):
                rows.append((v, i, TT, dd))
            if sweep_back:
                for v, i in zip(Vg[::-1], I[::-1] * np.exp(noise * rng.standard_normal(len(Vg)))):
                    rows.append((v, i, TT, dd))
            if both_polarities:
                for v, i in zip(Vg, I):
                    rows.append((-v, -i * np.exp(noise * rng.standard_normal()), TT, dd))
    return pd.DataFrame(rows, columns=["V (V)", "I (A)", "T (K)", "d (nm)"])


def preset(key, noise=0.05, seed=0):
    pr = PRESETS[key]
    df = generate(key, pr["params"], pr["V"], pr["T"], pr["d"], noise=noise, dev=pr["dev"], seed=seed)
    return df, DeviceInfo.from_dict(pr["dev"]), pr["params"]
